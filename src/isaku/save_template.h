/* Old releases created zero files. Recognize the absent name AND entirely
 * absent variable tables; retain every progress/heap byte when reading them.
 * Valid saves (including intentionally disabled audio) are left unchanged. */
static inline bool isaku_repair_empty_save(uint8_t *data)
{
    for (unsigned i = 0; i < 128; i++)
        if (data[i]) return false;
    for (unsigned i = 0x880; i < 0xa48; i++)
        if (data[i]) return false;
    memcpy(data, isaku_save_template, 128);
    memcpy(data + 0x880, isaku_save_template + 0x880, 0xa48 - 0x880);
    return true;
}
